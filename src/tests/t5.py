import asyncio
from playwright.async_api import async_playwright
from web import *
async def newpage(b,scheme="light"):
    ctx=await b.new_context(viewport={"width":400,"height":820},color_scheme=scheme)
    page=await ctx.new_page();page.errs=[]
    page.on("pageerror",lambda e:page.errs.append(str(e)))
    await page.add_init_script(path=SC+"mock.js")
    await page.goto("file:///mnt/user-data/outputs/buzunar.html");await page.wait_for_timeout(3000)
    await page.click("#sheet button:has-text('Sări peste')");await page.wait_for_timeout(500)
    return ctx,page
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        # 1. legacy auto items without car -> migrated and grouped (grandfathered even above the free limit)
        ctx,page=await newpage(b)
        await page.evaluate("""S.items=[{id:'a1',g:'auto',t:'itp',n:'B 123 ABC',d:plus(20),rep:24},{id:'a2',g:'auto',t:'rca',n:'b123abc',d:plus(25),rep:12},{id:'a3',g:'auto',t:'ulei',n:'Logan',d:plus(50),rep:12},{id:'a4',g:'auto',t:'rev',n:'',d:plus(60),rep:12}];save();render()""")
        await page.wait_for_timeout(400)
        cars=await page.evaluate("S.cars.map(c=>c.n)")
        chk("migration: plates that normalise equal share one car",cars==["B 123 ABC","Logan","Mașina mea"],cars)
        chk("migration: every auto item linked",await page.evaluate("S.items.every(x=>x.g!='auto'||S.cars.some(c=>c.id==x.car))"))
        chk("migration persisted",await page.evaluate("JSON.parse(localStorage.getItem('buzunar.v2')).cars.length")==3)
        await page.click("#main >> button:has-text('Auto')");await page.wait_for_timeout(700)
        t=await page.inner_text("#main")
        chk("auto view: heading per car","🚗 B 123 ABC" in t and "🚗 Logan" in t and "🚗 Mașina mea" in t,t[:400])
        chk("auto view: items under cars","ITP · B 123 ABC" in t and "Schimb ulei · Logan" in t)
        chk("auto view: add-car button marked Control for free","Adaugă mașină · Control" in t,t[-200:])
        await page.screenshot(path=SC+"n_cars.png")
        # 2. free user: second car blocked
        await page.click("#main >> button:has-text('Adaugă mașină')");await page.wait_for_timeout(600)
        s=await page.inner_text("#sheet")
        chk("free: new car opens Control",("Control" in s and "Mașini" in s and "nelimitate" in s) and "Mașină nouă" not in s,s[:300])
        await page.click("#sheet >> text=Închide");await page.wait_for_timeout(400)
        # 3. new item via form: choose existing car by chip, no new car
        await page.click("#main >> button:text-is('Adaugă')");await page.wait_for_timeout(600)
        await page.click("#sheet >> button:text-is('Auto')");await page.wait_for_timeout(300)
        s=await page.inner_text("#sheet")
        chk("form: car chips + new",("Mașina" in s) and "B 123 ABC" in s and "Logan" in s and "+ Mașină nouă" in s,s[:400])
        await page.click("#sheet >> button:text-is('Logan')");await page.wait_for_timeout(300)
        await page.click("#sheet >> button:text-is('RCA')");await page.wait_for_timeout(300)
        await page.fill("#f_d",await page.evaluate("plus(100)"))
        await page.click("#sheet >> text=Salvează");await page.wait_for_timeout(500)
        chk("form: item attached to Logan, no extra car",await page.evaluate("S.cars.length")==3 and await page.evaluate("S.items.some(x=>x.t=='rca'&&x.n=='Logan'&&S.cars.find(c=>c.id==x.car).n=='Logan')"))
        # 4. typing a plate that matches an existing car does not create a car or hit the limit
        await page.click("#main >> button:text-is('Adaugă')");await page.wait_for_timeout(500)
        await page.click("#sheet >> button:text-is('Auto')");await page.wait_for_timeout(300)
        await page.click("#sheet >> button:text-is('+ Mașină nouă')");await page.wait_for_timeout(300)
        await page.fill("#f_n","b 123abc");await page.fill("#f_d",await page.evaluate("plus(90)"))
        await page.click("#sheet >> button:text-is('Rovinietă')");await page.wait_for_timeout(200)
        await page.fill("#f_n","b 123abc")
        await page.click("#sheet >> text=Salvează");await page.wait_for_timeout(500)
        chk("matching plate reuses car",await page.evaluate("S.cars.length")==3 and await page.evaluate("S.items.some(x=>x.t=='rov'&&S.cars.find(c=>c.id==x.car).n=='B 123 ABC')"),await page.evaluate("JSON.stringify(S.cars.map(c=>c.n))"))
        # 5. a really new car name is blocked for free users and keeps nothing
        await page.click("#main >> button:text-is('Adaugă')");await page.wait_for_timeout(500)
        await page.click("#sheet >> button:text-is('Auto')");await page.wait_for_timeout(300)
        await page.click("#sheet >> button:text-is('+ Mașină nouă')");await page.wait_for_timeout(300)
        await page.fill("#f_n","CJ 99 XYZ");await page.fill("#f_d",await page.evaluate("plus(80)"))
        await page.click("#sheet >> text=Salvează");await page.wait_for_timeout(600)
        chk("free: new plate blocked, no car created",await page.evaluate("S.cars.length")==3 and "Control" in await page.inner_text("#sheet"))
        await page.click("#sheet >> text=Activează Control");await page.wait_for_timeout(500)
        # 6. with Control: add car from the auto view, then add a term for it
        await page.click("#main >> button:has-text('Adaugă mașină')");await page.wait_for_timeout(500)
        await page.fill("#k_n","CJ 99 XYZ");await page.click("#sheet >> text=Salvează");await page.wait_for_timeout(500)
        t=await page.inner_text("#main")
        chk("pro: car added, empty state shown","🚗 CJ 99 XYZ" in t and "Nu are termene încă" in t,t[-300:])
        await page.click("#main >> button:has-text('Adaugă un termen')");await page.wait_for_timeout(500)
        chk("add-term-for-car preselects the car",await page.is_visible("#sheet button.on:has-text('CJ 99 XYZ')"))
        await page.fill("#f_d",await page.evaluate("plus(70)"));await page.click("#sheet >> text=Salvează");await page.wait_for_timeout(500)
        chk("term landed under new car","ITP · CJ 99 XYZ" in await page.inner_text("#main"))
        # 7. rename car updates titles
        await page.click("#main >> .gt.car:has-text('Logan') >> button:has-text('Editează')");await page.wait_for_timeout(500)
        await page.fill("#k_n","Dacia Logan");await page.click("#sheet >> text=Salvează");await page.wait_for_timeout(500)
        t=await page.inner_text("#main")
        chk("rename propagates","Schimb ulei · Dacia Logan" in t and "RCA · Dacia Logan" in t and "· Logan" not in t.replace("Dacia Logan",""),t[:500])
