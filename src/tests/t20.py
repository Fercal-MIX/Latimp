U="http://localhost:8767/"
async def route(ctx,fail=False):
    async def h(r):
        if fail: await r.abort()
        else: await r.fulfill(status=200,content_type="application/javascript",body=FAKE)
    await ctx.route("**/cdn.jsdelivr.net/**",h)
    await ctx.route("**/fonts.googleapis.com/**",lambda r:r.abort())
async def skip(pg):
    for t in ["Sări peste","Mai târziu"]:
        try:
            await pg.wait_for_selector(f"#sheet button:has-text('{t}')",timeout=6000)
            await pg.click(f"#sheet button:has-text('{t}')");await pg.wait_for_timeout(700)
        except Exception: pass
